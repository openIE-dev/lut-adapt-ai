class RMSNorm(nn.Module):
    def __init__(self, dim: int, eps: float = 1e-6):
        super().__init__()
        self.weight = nn.Parameter(torch.ones(dim))
        self.eps = eps

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return x * torch.rsqrt(x.pow(2).mean(dim=-1, keepdim=True) + self.eps) * self.weight


def _apply_rope_1d(q: torch.Tensor, k: torch.Tensor, offset: int = 0) -> tuple[torch.Tensor, torch.Tensor]:
    # q, k: [B, H, T, Dh]
    dh = q.size(-1)
    t = q.size(2)
    pos = torch.arange(offset, offset + t, device=q.device, dtype=q.dtype)
    freqs = 1.0 / (10000.0 ** (torch.arange(0, dh, 2, device=q.device, dtype=q.dtype) / dh))
    angles = torch.outer(pos, freqs).view(1, 1, t, dh // 2)
    cos_a, sin_a = torch.cos(angles), torch.sin(angles)

    def rot(x: torch.Tensor) -> torch.Tensor:
        x0, x1 = x[..., 0::2], x[..., 1::2]
        return torch.stack([x0 * cos_a - x1 * sin_a, x0 * sin_a + x1 * cos_a], dim=-1).flatten(-2)

    return rot(q), rot(k)


class CausalTransformerBlock(nn.Module):
    def __init__(self, d_model: int, n_heads: int):
        super().__init__()
        self.n_heads = n_heads
        self.d_head = d_model // n_heads
        self.norm1 = RMSNorm(d_model)
        self.qkv = nn.Linear(d_model, 3 * d_model, bias=False)
        self.o_proj = nn.Linear(d_model, d_model, bias=False)
        self.norm2 = RMSNorm(d_model)
        hidden = int(d_model * 8 / 3)
        self.w_gate = nn.Linear(d_model, hidden, bias=False)
        self.w_up = nn.Linear(d_model, hidden, bias=False)
        self.w_down = nn.Linear(hidden, d_model, bias=False)

    def forward(
        self,
        x: torch.Tensor,
        kv_cache: tuple[torch.Tensor, torch.Tensor] | None = None,
    ) -> tuple[torch.Tensor, tuple[torch.Tensor, torch.Tensor]]:
        B, T, D = x.shape
        h = self.norm1(x)
        qkv = self.qkv(h).view(B, T, 3, self.n_heads, self.d_head)
        q = qkv[:, :, 0].transpose(1, 2)
        k = qkv[:, :, 1].transpose(1, 2)
        v = qkv[:, :, 2].transpose(1, 2)

        offset = 0 if kv_cache is None else kv_cache[0].size(2)
        q, k = _apply_rope_1d(q, k, offset=offset)
        if kv_cache is not None:
            k = torch.cat([kv_cache[0], k], dim=2)
            v = torch.cat([kv_cache[1], v], dim=2)

        scores = (q @ k.transpose(-2, -1)) * (1.0 / math.sqrt(self.d_head))
        if T > 1:
            S = k.size(2)
            q_idx = torch.arange(offset, offset + T, device=x.device)[:, None]
            k_idx = torch.arange(S, device=x.device)[None, :]
            scores = scores.masked_fill(k_idx > q_idx, float("-inf"))
        attn = F.softmax(scores, dim=-1) @ v
        x = x + self.o_proj(attn.transpose(1, 2).contiguous().view(B, T, D))

        h2 = self.norm2(x)
        x = x + self.w_down(F.silu(self.w_gate(h2)) * self.w_up(h2))
        return x, (k, v)


class CausalTransformerLM(nn.Module):
    """Llama-3 / Qwen-3 architecture byte-level Causal LM with exact KV-Cache."""

    def __init__(self, d_model: int = 192, n_layers: int = 3, n_heads: int = 4):
        super().__init__()
        self.d_model = d_model
        self.emb = nn.Embedding(256, d_model)
        self.blocks = nn.ModuleList([CausalTransformerBlock(d_model, n_heads) for _ in range(n_layers)])
        self.norm_f = RMSNorm(d_model)
        self.lm_head = nn.Linear(d_model, 256, bias=False)

    def count_step_flops(self, ctx_len: int) -> int:
        # 2 * params + attention KV dot-products across ctx_len
        param_flops = 2 * sum(p.numel() for p in self.parameters())
        attn_flops = len(self.blocks) * 4 * self.d_model * ctx_len
        return param_flops + attn_flops

    def forward_train(self, seq: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        h = self.emb(seq)
        for blk in self.blocks:
            h, _ = blk(h, kv_cache=None)
        h = self.norm_f(h)
        return self.lm_head(h), h

    @torch.no_grad()
    def generate_kv_cached(self, prompt: torch.Tensor, gen_len: int) -> torch.Tensor:
        B = prompt.size(0)
        caches: list[tuple[torch.Tensor, torch.Tensor] | None] = [None] * len(self.blocks)
        h = self.emb(prompt)
        for i, blk in enumerate(self.blocks):
            h, caches[i] = blk(h, kv_cache=None)
        logits = self.lm_head(self.norm_f(h[:, -1:]))
        next_tok = logits.argmax(dim=-1)  # [B, 1]
        out = [next_tok]

        for _ in range(gen_len - 1):
            h = self.emb(next_tok)
            for i, blk in enumerate(self.blocks):
                h, caches[i] = blk(h, kv_cache=caches[i])
            next_tok = self.lm_head(self.norm_f(h)).argmax(dim=-1)
            out.append(next_tok)
        return torch.cat(out, dim=1)


