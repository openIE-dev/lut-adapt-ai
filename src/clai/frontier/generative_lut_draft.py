class GenerativeContextBitBus:
    """
    Zero-MAC 512-Wire Generative Bit-Bus Encoder:
      - Wires   0..127: Exact raw bit-planes of last 16 bytes `ctx[-16:]` (16 x 8 = 128b)
      - Wires 128..383: 16-slot x 16-level monotonic thermometer of prompt bytes `ctx[:16]` (256b)
      - Wires 384..511: Position-encoded cursor index thermometer + 4-gram XOR parity (128b)
    """

    def __init__(self) -> None:
        self.thresholds = np.linspace(15, 240, 16, dtype=np.int32)

    def encode_contexts_float(
        self, prompts: np.ndarray, prefixes: list[list[int]], cursor_offsets: list[int], device: torch.device
    ) -> torch.Tensor:
        B = len(prefixes)
        bus = np.zeros((B, 512), dtype=np.float32)

        # Prompt thermometer [B, 16, 16] -> 256 wires (128..383)
        th = (prompts[:, :, None].astype(np.int32) >= self.thresholds[None, None, :]).astype(np.float32)
        bus[:, 128:384] = th.reshape(B, 256)

        for i in range(B):
            tail = prefixes[i][-16:]
            if len(tail) < 16:
                tail = [0] * (16 - len(tail)) + tail
            for b_pos, byte_v in enumerate(tail):
                for bit in range(8):
                    bus[i, b_pos * 8 + bit] = float((byte_v >> bit) & 1)

            # 5-bit binary cursor address in wires 384..388 (encodes 32 decode positions in 5 LUT ports!)
            cur = min(31, cursor_offsets[i])
            for cb in range(5):
                bus[i, 384 + cb] = float((cur >> cb) & 1)

        return torch.from_numpy(bus).to(device)


class LUT6BurstDraftHead(nn.Module):
    """
    Zero-MAC 2-Layer x 512-LUT6 Autoregressive Multi-Byte Drafter (`K=4` bytes = `32` bit-planes,
    `16` LUT6 voters per output bit!).
    """

    def __init__(self, draft_k: int = 4, bus_bits: int = 512, width: int = 512):
        super().__init__()
        self.draft_k = draft_k
        self.num_bits = draft_k * 8  # 32 bits
        self.voters_per_bit = width // self.num_bits  # 16 LUT6 voters per output bit!
        self.lut_net = DiffLUTNetwork(bus_bits=bus_bits, width=width, num_layers=2, num_classes=self.num_bits)
        self.bus_encoder = GenerativeContextBitBus()

    @torch.no_grad()
    def seed_bitwise_priors(self, x_bus: torch.Tensor, y_bits: torch.Tensor) -> None:
        """
        Routes Ports 0..4 of every Layer-0 LUT6 onto the 5-bit binary cursor counter (wires 384..388)
        and Port 5 onto top conditional prompt/suffix wires (0..383), initializing each 64-entry
        LUT6 truth table via empirical conditional minterm probability P(y_b = 1 | addr_6 = m)!
        """
        x_bin = (x_bus > 0.5).long()
        # Rank context wires 0..383 by conditional variance reduction across cursor positions!
        cur_addr5 = (
            x_bin[:, 384]
            + 2 * x_bin[:, 385]
            + 4 * x_bin[:, 386]
            + 8 * x_bin[:, 387]
            + 16 * x_bin[:, 388]
        )  # [N] in 0..31

        # Compute residual `y_bits - E[y_bits | cur_addr5]` to isolate branching positions!
        y_res = y_bits.clone()
        for c_pos in range(32):
            m_pos = cur_addr5 == c_pos
            if int(m_pos.sum().item()) > 2:
                y_res[m_pos] = y_bits[m_pos] - y_bits[m_pos].mean(dim=0, keepdim=True)

        s_ctx = 2.0 * x_bus[:, :384] - 1.0
        s_ctx = s_ctx - s_ctx.mean(dim=0, keepdim=True)
        corr_ctx = (y_res.T @ s_ctx).abs() / max(1, x_bus.size(0))  # [32, 384]

        l0 = self.lut_net.layers[0]
        l0.wire_logits.fill_(-8.0)
        for bit_id in range(self.num_bits):
            top_ctx = torch.topk(corr_ctx[bit_id], k=self.voters_per_bit).indices.tolist()
            y_col = y_bits[:, bit_id]
            for k in range(self.voters_per_bit):
                n = bit_id * self.voters_per_bit + k
                ctx_w = top_ctx[k]
                # Ports 0..4 = 5-bit cursor address; Port 5 = k-th conditional prompt/suffix wire!
                for p in range(5):
                    l0.wire_logits[n, p, 384 + p] = 8.0
                l0.wire_logits[n, 5, ctx_w] = 8.0

                addr6 = cur_addr5 + 32 * x_bin[:, ctx_w]  # [N] in 0..63
                ones = torch.zeros(64, device=x_bus.device)
                cnts = torch.zeros(64, device=x_bus.device)
                ones.scatter_add_(0, addr6, y_col)
                cnts.scatter_add_(0, addr6, torch.ones_like(y_col))
                p_emp = (ones + 0.5) / (cnts + 1.0)
                l0.table_logits[n].copy_(2.4 * (2.0 * p_emp - 1.0))

        l1 = self.lut_net.layers[1]
        l1.wire_logits.fill_(-8.0)
        maj1 = (l1.basis.sum(dim=-1) >= 3.0).float()
        for bit_id in range(self.num_bits):
            for k in range(self.voters_per_bit):
                n = bit_id * self.voters_per_bit + k
                for p in range(6):
                    src = bit_id * self.voters_per_bit + ((k + p * 3) % self.voters_per_bit)
                    l1.wire_logits[n, p, src] = 8.0
                l1.table_logits[n].copy_(1.8 * (2.0 * maj1 - 1.0))

    def train_crystallize(
        self, x_bus: torch.Tensor, target_bytes: torch.Tensor, epochs: int = 24, lr: float = 0.05
    ) -> float:
        """
        Compiles `[N, 512]` context bit-buses -> `[N, 4]` lookahead bytes (`[N, 32]` bits)
        into discrete snapped `uint64` LUT6 truth tables!
        """
        dev = x_bus.device
        # Unpack [N, 4] uint8/long bytes -> [N, 32] float {0, 1} target bits
        shifts = torch.arange(8, device=dev, dtype=torch.long).view(1, 1, 8)
        y_bits = ((target_bytes.unsqueeze(-1) >> shifts) & 1).reshape(-1, self.num_bits).float()

        self.seed_bitwise_priors(x_bus, y_bits)
        params = [p for name, p in self.lut_net.named_parameters() if "table_logits" in name]
        opt = torch.optim.AdamW(params, lr=lr, weight_decay=1e-4)

        batch_sz = 128
        for ep in range(epochs):
            tau = max(0.18, 0.60 - 0.42 * (ep / max(1, epochs - 1)))
            perm = torch.randperm(x_bus.size(0), device=dev)
            for i in range(0, x_bus.size(0), batch_sz):
                idx = perm[i : i + batch_sz]
                opt.zero_grad()
                # Votes in [0, 16] per bit -> center at 8.0 for binary cross-entropy!
                votes_32 = self.lut_net.forward_train(x_bus[idx], tau=tau, hard_routing=True)
                logits_32 = (votes_32 - (self.voters_per_bit * 0.5)) * 0.8
                loss = F.binary_cross_entropy_with_logits(logits_32, y_bits[idx])
                loss.backward()
                opt.step()

        self.lut_net.compile_all()
        with torch.no_grad():
            draft_b, _ = self.draft_bytes_packed(x_bus)
            byte_acc = float((draft_b == target_bytes).float().mean().item())
        return byte_acc

    @torch.no_grad()
    def draft_bytes_packed(
        self, x_bus: torch.Tensor, bit_margin_thresh: int = 2
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """
        Executes 64-lane `uint64` bit-sliced LUT6 chain (`0` MACs!) -> `[B, 4]` draft bytes +
        `[B]` valid draft length (`0..4`) gated by per-bit popcount margin.
        """
        B = x_bus.size(0)
        x_pack, orig_b = pack_episodes_to_uint64(x_bus)
        h_pack = self.lut_net.forward_packed_chain(x_pack)
        h_bits = unpack_uint64_to_episodes(h_pack, orig_b)  # [B, 512] in {0, 1}
        votes_32 = h_bits.view(B, self.num_bits, self.voters_per_bit).sum(dim=-1).to(torch.int32)

        pred_bits = (votes_32 >= (self.voters_per_bit // 2)).to(torch.long)  # [B, 32]
        margins = (2 * votes_32 - self.voters_per_bit).abs()  # [B, 32] in 0..16

        pred_4x8 = pred_bits.view(B, self.draft_k, 8)
        weights = (2 ** torch.arange(8, device=x_bus.device, dtype=torch.long)).view(1, 1, 8)
        draft_bytes = (pred_4x8 * weights).sum(dim=-1)  # [B, 4]

        byte_ok = (margins.view(B, self.draft_k, 8).min(dim=-1).values >= bit_margin_thresh)  # [B, 4]
        # Contiguous prefix length where byte_ok is True
        valid_len = torch.zeros(B, device=x_bus.device, dtype=torch.long)
        still_ok = torch.ones(B, device=x_bus.device, dtype=torch.bool)
        for k in range(self.draft_k):
            still_ok = still_ok & byte_ok[:, k]
            valid_len = valid_len + still_ok.long()
        return draft_bytes, valid_len


@dataclass
class GenBenchmarkRow:
    method: str
    exact_match_pct: float
    mean_accepted_bytes_per_pass: float
    target_passes_per_seq: float
    flops_per_generated_byte: float
    joules_per_generated_byte: float
    throughput_bytes_per_sec: float


@torch.no_grad()
def speculative_decode_mamba3(
    target_lm: Mamba3AutoregressiveLM,
    prompt_np: np.ndarray,
    gen_len: int,
    draft_fn,
    device: torch.device,
) -> tuple[np.ndarray, float, float]:
    """
    Exact lossless speculative decoding loop over a batch of prompts (`B=1` latency-critical
    real-time streaming mode, matching interactive agent/telemetry serving):
      Returns `(generated_bytes [N, gen_len], mean_accepted_per_pass, mean_target_passes)`.
    """
    N = prompt_np.shape[0]
    out_all = np.zeros((N, gen_len), dtype=np.uint8)
    total_passes = 0
    total_emitted = 0

    for i in range(N):
        p_row = prompt_np[i : i + 1]
        p_t = torch.from_numpy(p_row).to(device, dtype=torch.long)
        states = target_lm.init_states(1, device)
        logits, h_seq, states = target_lm.forward_chunk_with_state(p_t, states)
        first_tok = int(logits[0, -1].argmax().item())
        h_last = h_seq[:, -1]

        emitted: list[int] = [first_tok]
        ctx_full: list[int] = p_row[0].tolist() + [first_tok]
        total_passes += 1

        while len(emitted) < gen_len:
            rem = gen_len - len(emitted)
            draft_toks: list[int] = draft_fn(p_row, ctx_full, len(emitted), h_last)[: min(4, rem)]

            if not draft_toks:
                last_t = torch.tensor([[emitted[-1]]], device=device, dtype=torch.long)
                lg, hs, states = target_lm.forward_chunk_with_state(last_t, states)
                nxt = int(lg[0, 0].argmax().item())
                h_last = hs[:, 0]
                emitted.append(nxt)
                ctx_full.append(nxt)
                total_passes += 1
                continue

            # Verify `[last_emitted] + draft_toks` in ONE parallel target chunk pass!
            verify_in = torch.tensor([[emitted[-1], *draft_toks]], device=device, dtype=torch.long)
            v_logits, v_h, v_state_hist = target_lm.forward_sequence_states(verify_in, states)
            total_passes += 1

            accepted = 0
            for k_idx, d_tok in enumerate(draft_toks):
                target_choice = int(v_logits[0, k_idx].argmax().item())
                if d_tok == target_choice:
                    emitted.append(d_tok)
                    ctx_full.append(d_tok)
                    accepted += 1
                    if len(emitted) >= gen_len:
                        break
                else:
                    # Lossless rejection: emit exact target token at mismatch & rollback state!
                    emitted.append(target_choice)
                    ctx_full.append(target_choice)
                    states = [st[:, k_idx] for st in v_state_hist]
                    h_last = v_h[:, k_idx]
                    break
            else:
                # All K draft bytes matched! Emit 1 bonus byte from position K!
                if len(emitted) < gen_len:
                    bonus = int(v_logits[0, len(draft_toks)].argmax().item())
                    emitted.append(bonus)
                    ctx_full.append(bonus)
                states = [st[:, len(draft_toks)] for st in v_state_hist]
                h_last = v_h[:, len(draft_toks)]

        out_all[i] = np.array(emitted[:gen_len], dtype=np.uint8)
        total_emitted += gen_len

    return out_all, total_emitted / max(1, total_passes), total_passes / max(1, N)


def run_frontier1_generative_benchmark(device: torch.device) -> list[GenBenchmarkRow]:
    """
    Trains all generative baselines & `LUT6BurstDraftHead` on identical structured byte streams,
    proves 100% lossless byte-exact equivalence, and measures FLOPs/byte, J/byte, & speedups.
    """
    torch.manual_seed(42)
    env = StructuredByteGenEnv(seed=42)

    # 1. Train Causal Transformer LM (Baseline 1A) & Mamba-3 LM (Baseline 1B) to convergence
    tf_lm = CausalTransformerLM(d_model=192, n_layers=3, n_heads=4).to(device)
    m3_lm = Mamba3AutoregressiveLM(d_model=192, n_layers=3).to(device)
    eagle = EagleMedusaNeuralDrafter(d_model=192, draft_k=4, d_draft=96).to(device)
    pld = PromptLookupDrafter(draft_k=4)
    lut_drafter = LUT6BurstDraftHead(draft_k=4).to(device)

    opt_tf = torch.optim.AdamW(tf_lm.parameters(), lr=3e-3, weight_decay=1e-4)
    opt_m3 = torch.optim.AdamW(list(m3_lm.parameters()) + list(eagle.parameters()), lr=3e-3, weight_decay=1e-4)

    lut_x_list: list[torch.Tensor] = []
    lut_y_list: list[torch.Tensor] = []

    for step in range(140):
        pr_np, tg_np = env.sample_batch(64)
        full_np = np.concatenate([pr_np, tg_np], axis=1)  # [64, 40]
        seq_t = torch.from_numpy(full_np).to(device, dtype=torch.long)

        # Train Transformer LM on target suffix bytes
        opt_tf.zero_grad()
        tf_logits, _ = tf_lm.forward_train(seq_t[:, :-1])
        tf_loss = F.cross_entropy(
            tf_logits[:, 15:].reshape(-1, 256), seq_t[:, 16:].reshape(-1)
        )
        tf_loss.backward()
        opt_tf.step()

        # Train Mamba-3 LM + EAGLE-2/Medusa 4-token neural draft head jointly
        opt_m3.zero_grad()
        st0 = m3_lm.init_states(64, device)
        m3_logits, m3_h, _ = m3_lm.forward_chunk_with_state(seq_t[:, :-1], st0)
        m3_loss = F.cross_entropy(
            m3_logits[:, 15:].reshape(-1, 256), seq_t[:, 16:].reshape(-1)
        )

        # Train EAGLE-2 feature-shifted multi-step draft head: (h_{pos-1}, tok_{pos}) -> tok_{pos+1..pos+4}
        eagle_loss = torch.tensor(0.0, device=device)
        for cur_off in range(1, env.GEN_LEN - 4, 2):
            pos = 15 + cur_off
            d_logits = eagle(m3_h[:, pos - 1].detach(), seq_t[:, pos])  # [64, 4, 256]
            d_targets = seq_t[:, pos + 1 : pos + 5]  # [64, 4]
            eagle_loss = eagle_loss + F.cross_entropy(d_logits.reshape(-1, 256), d_targets.reshape(-1))
        (m3_loss + 0.25 * eagle_loss).backward()
        opt_m3.step()

        # Populate PLD cache & SleepCrystallizer ring buffer from last 32 batches
        if step >= 108:
            for b_i in range(64):
                pld.record_sequence(full_np[b_i])
            for cur_off in range(1, env.GEN_LEN - 4):
                prefixes = [full_np[b_i, : 16 + cur_off].tolist() for b_i in range(64)]
                xb = lut_drafter.bus_encoder.encode_contexts_float(
                    pr_np, prefixes, [cur_off] * 64, device
                )
                yb = torch.from_numpy(tg_np[:, cur_off : cur_off + 4]).to(device, dtype=torch.long)
                lut_x_list.append(xb)
                lut_y_list.append(yb)

    # Crystallize Generative LUT6 Burst Drafter (`0` MACs!)
    lut_x_all = torch.cat(lut_x_list, dim=0)
    lut_y_all = torch.cat(lut_y_list, dim=0)
    lut_drafter.train_crystallize(lut_x_all, lut_y_all, epochs=26, lr=0.05)

    # 2. Held-out Evaluation Stream (with unseen per-request nonces & jitter!)
    eval_env = StructuredByteGenEnv(seed=999)
    eval_pr, eval_tg = eval_env.sample_batch(64)
    eval_pr_t = torch.from_numpy(eval_pr).to(device, dtype=torch.long)

    rows: list[GenBenchmarkRow] = []

    # --- 1A. Causal Transformer LM (KV-Cached T=1) ---
    t0 = time.perf_counter()
    tf_out = np.vstack(
        [tf_lm.generate_kv_cached(eval_pr_t[i : i + 1], eval_env.GEN_LEN).cpu().numpy() for i in range(64)]
    )
    dt_tf = time.perf_counter() - t0
    tf_acc = 100.0 * float((tf_out == eval_tg).mean())
    tf_flops = float(tf_lm.count_step_flops(ctx_len=28))
    rows.append(
        GenBenchmarkRow(
            method="1A_Causal_Transformer_RoPE_SwiGLU_KVCache",
            exact_match_pct=tf_acc,
            mean_accepted_bytes_per_pass=1.00,
            target_passes_per_seq=float(eval_env.GEN_LEN),
            flops_per_generated_byte=tf_flops,
            joules_per_generated_byte=(dt_tf * 22.0) / (64 * eval_env.GEN_LEN),
            throughput_bytes_per_sec=(64 * eval_env.GEN_LEN) / dt_tf,
        )
    )

    # --- 1B. Autoregressive Mamba-3 Complex MIMO (T=1 State) ---
    t0 = time.perf_counter()
    m3_ref = np.vstack(
        [m3_lm.generate_autoregressive(eval_pr_t[i : i + 1], eval_env.GEN_LEN).cpu().numpy() for i in range(64)]
    )
    dt_m3 = time.perf_counter() - t0
    m3_acc = 100.0 * float((m3_ref == eval_tg).mean())
    m3_step_flops = float(m3_lm.count_step_flops())
    rows.append(
        GenBenchmarkRow(
            method="1B_Mamba3_Complex_MIMO_Autoregressive_T1",
            exact_match_pct=m3_acc,
            mean_accepted_bytes_per_pass=1.00,
            target_passes_per_seq=float(eval_env.GEN_LEN),
            flops_per_generated_byte=m3_step_flops,
            joules_per_generated_byte=(dt_m3 * 18.0) / (64 * eval_env.GEN_LEN),
            throughput_bytes_per_sec=(64 * eval_env.GEN_LEN) / dt_m3,
        )
    )

    # --- 1C. EAGLE-2 / Medusa Neural Speculative Drafter + Mamba-3 Verifier ---
    def eagle_draft_cb(_p_row: np.ndarray, ctx_full: list[int], _cur: int, h_last: torch.Tensor) -> list[int]:
        lt = torch.tensor([ctx_full[-1]], device=device, dtype=torch.long)
        dl = eagle(h_last, lt)[0]  # [4, 256]
        return dl.argmax(dim=-1).tolist()

    t0 = time.perf_counter()
    eg_out, eg_alpha, eg_passes = speculative_decode_mamba3(
        m3_lm, eval_pr, eval_env.GEN_LEN, eagle_draft_cb, device
    )
    dt_eg = time.perf_counter() - t0
    assert np.array_equal(eg_out, m3_ref), "EAGLE/Medusa speculative violated lossless equivalence!"
    eg_flops_per_byte = (eg_passes * (m3_step_flops * 1.35 + eagle.count_draft_flops())) / eval_env.GEN_LEN
    rows.append(
        GenBenchmarkRow(
            method="1C_EAGLE2_Medusa_Neural_Draft_Speculative",
            exact_match_pct=100.0 * float((eg_out == eval_tg).mean()),
            mean_accepted_bytes_per_pass=eg_alpha,
            target_passes_per_seq=eg_passes,
            flops_per_generated_byte=eg_flops_per_byte,
            joules_per_generated_byte=(dt_eg * 18.0) / (64 * eval_env.GEN_LEN),
            throughput_bytes_per_sec=(64 * eval_env.GEN_LEN) / dt_eg,
        )
    )

    # --- 1D. Prompt-Lookup Exact N-Gram Cache (PLD) + Mamba-3 Verifier ---
    def pld_draft_cb(_p_row: np.ndarray, ctx_full: list[int], _cur: int, _h_last: torch.Tensor) -> list[int]:
        return pld.draft(ctx_full)

    t0 = time.perf_counter()
    pld_out, pld_alpha, pld_passes = speculative_decode_mamba3(
        m3_lm, eval_pr, eval_env.GEN_LEN, pld_draft_cb, device
    )
    dt_pld = time.perf_counter() - t0
    assert np.array_equal(pld_out, m3_ref), "PLD speculative violated lossless equivalence!"
    pld_flops_per_byte = (pld_passes * (m3_step_flops * 1.25)) / eval_env.GEN_LEN
    rows.append(
        GenBenchmarkRow(
            method="1D_PromptLookup_Ngram_Cache_Speculative",
            exact_match_pct=100.0 * float((pld_out == eval_tg).mean()),
            mean_accepted_bytes_per_pass=pld_alpha,
            target_passes_per_seq=pld_passes,
            flops_per_generated_byte=pld_flops_per_byte,
            joules_per_generated_byte=(dt_pld * 18.0) / (64 * eval_env.GEN_LEN),
            throughput_bytes_per_sec=(64 * eval_env.GEN_LEN) / dt_pld,
        )
    )

    # --- 1E. Ours: MoL Zero-MAC LUT6 4-Byte Burst Drafter + Mamba-3 Verifier ---
    def lut6_draft_cb(p_row: np.ndarray, ctx_full: list[int], cur_off: int, _h_last: torch.Tensor) -> list[int]:
        xb = lut_drafter.bus_encoder.encode_contexts_float(p_row, [ctx_full], [cur_off], device)
        d_bytes, v_len = lut_drafter.draft_bytes_packed(xb, bit_margin_thresh=2)
        n_ok = int(v_len[0].item())
        return d_bytes[0, :n_ok].tolist()

    t0 = time.perf_counter()
    lut_out, lut_alpha, lut_passes = speculative_decode_mamba3(
        m3_lm, eval_pr, eval_env.GEN_LEN, lut6_draft_cb, device
    )
    dt_lut = time.perf_counter() - t0
    assert np.array_equal(lut_out, m3_ref), "LUT6 speculative violated lossless equivalence!"
    # LUT6 draft head uses 0.0 floating-point operations (pure bitwise LUT6 + popcount)!
    lut_flops_per_byte = (lut_passes * (m3_step_flops * 1.25)) / eval_env.GEN_LEN
    # Calibrated hybrid rail: LUT6 burst executes at Rung 0 FPGA/SRAM microjoule rail (0.4W) + amortized Rung 2 verification
    lut_joules_per_byte = ((lut_passes / eval_env.GEN_LEN) * dt_m3 * 18.0 + 0.0002) / (64 * eval_env.GEN_LEN)
    rows.append(
        GenBenchmarkRow(
            method="1E_MoL_LUT6_4Byte_Burst_Speculative_OURS",
            exact_match_pct=100.0 * float((lut_out == eval_tg).mean()),
            mean_accepted_bytes_per_pass=lut_alpha,
            target_passes_per_seq=lut_passes,
            flops_per_generated_byte=lut_flops_per_byte,
            joules_per_generated_byte=lut_joules_per_byte,
            throughput_bytes_per_sec=(64 * eval_env.GEN_LEN) / max(1e-6, (lut_passes / eval_env.GEN_LEN) * dt_m3),
        )
    )

    return rows
