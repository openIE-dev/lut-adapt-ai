class StructuredByteGenEnv:
    """
    Controlled variable-context structured JSON/SQL command generation benchmark (`vocab = 256`).
    Prompts (`16` bytes) carry continuous sensor/load parameters + per-request random ID noise
    (defeating naive exact-prefix memorization while preserving underlying Boolean/threshold laws),
    mapping deterministically to `24`-byte structured JSON/action completions.
    Supports live `mutate_schema()` (`v1` JSON -> `v2` compact RPC) to test post-drift adaptation.
    """

    PROMPT_LEN = 16
    GEN_LEN = 24

    TEMPLATES_V1: list[bytes] = [
        b'{"v":1,"op":"HOLD","q":0}',  # 25B -> trimmed/padded to 24B
        b'{"v":1,"op":"SCAL","q":1}',
        b'{"v":1,"op":"DROP","q":2}',
        b'{"v":1,"op":"ISOL","q":3}',
    ]
    TEMPLATES_V2: list[bytes] = [
        b'[v2:OK:PASSIVE_IDLE:000]',
        b'[v2:GO:BURST_EXPAND:111]',
        b'[v2:NO:PACKET_PURGE:222]',
        b'[v2:XX:QUARANTINE_Z:333]',
    ]

    def __init__(self, seed: int = 42):
        self.rng = np.random.default_rng(seed)
        self.schema_v2 = False

    def mutate_schema(self) -> None:
        self.schema_v2 = not self.schema_v2

    def sample_batch(self, batch_size: int) -> tuple[np.ndarray, np.ndarray]:
        prompts = np.zeros((batch_size, self.PROMPT_LEN), dtype=np.uint8)
        targets = np.zeros((batch_size, self.GEN_LEN), dtype=np.uint8)
        templates = self.TEMPLATES_V2 if self.schema_v2 else self.TEMPLATES_V1

        for i in range(batch_size):
            # Slots 0..3: two independent continuous prompt variables (op_cls 0..3 & quota_tier 0..3
            # = 16 parameterized JSON outputs) + Slots 4..15 per-request random trace/nonce IDs!
            cls_id = int(self.rng.integers(0, 4))
            tier_id = int(self.rng.integers(0, 4))
            load_val = 32 + cls_id * 62 + int(self.rng.integers(-16, 17))
            lat_val = 32 + tier_id * 62 + int(self.rng.integers(-16, 17))
            prompts[i, 0] = np.clip(load_val, 1, 254)
            prompts[i, 1] = np.clip(lat_val, 1, 254)
            prompts[i, 2] = 0x90 + cls_id * 0x18 + int(self.rng.integers(0, 6))
            prompts[i, 3] = 0x90 + tier_id * 0x18 + int(self.rng.integers(0, 6))
            prompts[i, 4:] = self.rng.integers(32, 126, size=(12,), dtype=np.uint8)

            if not self.schema_v2:
                op_str = ("HOLD", "SCAL", "DROP", "ISOL")[cls_id]
                tpl = f'{{"v":1,"op":"{op_str}","q":{tier_id}}}'.encode("ascii")
            else:
                op_str = ("PASSIVE_IDLE", "BURST_EXPAND", "PACKET_PURGE", "QUARANTINE_Z")[cls_id]
                tpl = f"[v2:{op_str}:q={tier_id}00]".encode("ascii")
            targets[i] = np.frombuffer(tpl[: self.GEN_LEN].ljust(self.GEN_LEN, b" "), dtype=np.uint8)
        return prompts, targets


