class EagleMedusaNeuralDrafter(nn.Module):
    """
    Lightweight FP32 Neural Speculative Draft Head (`EAGLE-2 / Medusa` family):
    Conditioned on the target model's last hidden state `h_t` + last emitted token embedding,
    predicts `K = 4` future bytes in parallel using `K` learned SwiGLU draft heads.
    """

    def __init__(self, d_model: int = 192, draft_k: int = 4, d_draft: int = 96):
        super().__init__()
        self.draft_k = draft_k
        self.tok_emb = nn.Embedding(256, d_draft)
        self.fusion = nn.Linear(d_model + d_draft, d_draft)
        self.heads = nn.ModuleList([nn.Linear(d_draft, 256) for _ in range(draft_k)])

    def count_draft_flops(self) -> int:
        return 2 * sum(p.numel() for p in self.parameters())

    def forward(self, h_target: torch.Tensor, last_tok: torch.Tensor) -> torch.Tensor:
        # h_target: [B, D], last_tok: [B] -> [B, K, 256]
        te = self.tok_emb(last_tok)
        z = F.silu(self.fusion(torch.cat([h_target, te], dim=-1)))
        return torch.stack([head(z) for head in self.heads], dim=1)


