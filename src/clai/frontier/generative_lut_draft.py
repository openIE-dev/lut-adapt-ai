class Mamba3AutoregressiveLM(nn.Module):
    """
    O(1)-state Complex-RoPE MIMO State-Space Byte LM supporting both:
      - `step_recurrent` (`T=1` state update)
      - `verify_draft_chunk` (parallel verification of `K` speculative draft bytes in 1 pass!)
    """

    def __init__(self, d_model: int = 192, n_layers: int = 3):
        super().__init__()
        self.d_model = d_model
        self.n_layers = n_layers
        self.emb = nn.Embedding(256, d_model)
        self.in_projs = nn.ModuleList([nn.Linear(d_model, 3 * d_model, bias=False) for _ in range(n_layers)])
        self.dt_projs = nn.ModuleList([nn.Linear(d_model, d_model) for _ in range(n_layers)])
        self.out_projs = nn.ModuleList([nn.Linear(d_model, d_model, bias=False) for _ in range(n_layers)])
        self.norms = nn.ModuleList([RMSNorm(d_model) for _ in range(n_layers)])
        self.norm_f = RMSNorm(d_model)
        self.lm_head = nn.Linear(d_model, 256, bias=False)

    def count_step_flops(self) -> int:
        return 2 * sum(p.numel() for p in self.parameters())

    def init_states(self, batch_size: int, device: torch.device) -> list[torch.Tensor]:
        return [torch.zeros(batch_size, self.d_model, device=device) for _ in range(self.n_layers)]

    def forward_chunk_with_state(
        self, tokens: torch.Tensor, states: list[torch.Tensor]
    ) -> tuple[torch.Tensor, torch.Tensor, list[torch.Tensor]]:
        """Processes `T` tokens (`T=1` or `T=K+1` draft verification) updating recurrent states."""
        h = self.emb(tokens)  # [B, T, D]
        B, T, D = h.shape
        new_states: list[torch.Tensor] = []

        for l_idx in range(self.n_layers):
            u = self.norms[l_idx](h)
            z_x_c = self.in_projs[l_idx](u)
            gate, u_val, c_proj = z_x_c.chunk(3, dim=-1)
            alpha = torch.sigmoid(self.dt_projs[l_idx](u) - 1.5)  # decay in (0, 1)

            if T == 1:
                st = alpha[:, 0] * states[l_idx] + (1.0 - alpha[:, 0]) * u_val[:, 0]
                y = (st * torch.tanh(c_proj[:, 0])).unsqueeze(1)
                new_states.append(st)
            else:
                # Parallel prefix scan across small T (e.g. K+1=5 or T=40)
                st = states[l_idx]
                ys = []
                for t in range(T):
                    st = alpha[:, t] * st + (1.0 - alpha[:, t]) * u_val[:, t]
                    ys.append(st * torch.tanh(c_proj[:, t]))
                y = torch.stack(ys, dim=1)
                new_states.append(st)

            h = h + self.out_projs[l_idx](y * F.silu(gate))

        h_final = self.norm_f(h)
        return self.lm_head(h_final), h_final, new_states

    def forward_sequence_states(
        self, tokens: torch.Tensor, init_states: list[torch.Tensor]
    ) -> tuple[torch.Tensor, torch.Tensor, list[torch.Tensor]]:
        """Also returns intermediate per-step states `[T, B, D]` per layer for exact rollback!"""
        h = self.emb(tokens)
        B, T, _ = h.shape
        all_layer_states: list[torch.Tensor] = []

        for l_idx in range(self.n_layers):
            u = self.norms[l_idx](h)
            gate, u_val, c_proj = self.in_projs[l_idx](u).chunk(3, dim=-1)
            alpha = torch.sigmoid(self.dt_projs[l_idx](u) - 1.5)
            st = init_states[l_idx]
            st_hist = []
            ys = []
            for t in range(T):
                st = alpha[:, t] * st + (1.0 - alpha[:, t]) * u_val[:, t]
                st_hist.append(st)
                ys.append(st * torch.tanh(c_proj[:, t]))
            all_layer_states.append(torch.stack(st_hist, dim=1))  # [B, T, D]
            h = h + self.out_projs[l_idx](torch.stack(ys, dim=1) * F.silu(gate))

        h_final = self.norm_f(h)
        return self.lm_head(h_final), h_final, all_layer_states

    @torch.no_grad()
    def generate_autoregressive(self, prompt: torch.Tensor, gen_len: int) -> torch.Tensor:
        B = prompt.size(0)
        states = self.init_states(B, prompt.device)
        logits, _, states = self.forward_chunk_with_state(prompt, states)
        tok = logits[:, -1:].argmax(dim=-1)
        out = [tok]
        for _ in range(gen_len - 1):
            logits, _, states = self.forward_chunk_with_state(tok, states)
            tok = logits.argmax(dim=-1)
            out.append(tok)
        return torch.cat(out, dim=1)


