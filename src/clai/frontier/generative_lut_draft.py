class PromptLookupDrafter:
    """Exact 6-byte context suffix hash table (`PLD` / N-gram cache) with 0 Boolean generalization."""

    def __init__(self, draft_k: int = 4):
        self.draft_k = draft_k
        self.table: dict[bytes, bytes] = {}

    def record_sequence(self, full_bytes: np.ndarray) -> None:
        raw = bytes(full_bytes.tolist())
        for t in range(8, len(raw) - self.draft_k):
            key = raw[t - 6 : t]
            self.table[key] = raw[t : t + self.draft_k]

    def draft(self, ctx_bytes: list[int]) -> list[int]:
        if len(ctx_bytes) < 6:
            return []
        key = bytes(ctx_bytes[-6:])
        hit = self.table.get(key)
        return list(hit) if hit is not None else []


